"""
Run controller orchestrating subprocess execution, output polling, and status bar updates.
"""

from datetime import datetime
import os
import queue
from tkinter import messagebox
from typing import Any, Optional


class RunController:
    """Orchestrates background execution, output streaming, and completion handling.

    Usage
    -----
    controller = RunController(app)
    controller.run_active_tab()
    """

    def __init__(self, app_instance: Any) -> None:
        """Initialize the run controller.

        Parameters
        ------------
        app_instance: Any
            Reference to the main NFACTGuiApp window.

        Returns
        --------
            None: None object
                Initializes controller state.
        """
        self.app = app_instance
        self.output_queue: queue.Queue = queue.Queue()
        self.current_history_entry_id: Optional[str] = None
        self.process_start_time: Optional[datetime] = None

    def run_active_tab(self) -> None:
        """Validate and execute the command generated by the currently active tab.

        Parameters
        ------------
        None

        Returns
        --------
            None: None object
                Launches process or displays validation warnings.
        """
        if self.app.runner.is_running:
            return

        active_tab = self.app.get_active_tab_instance()
        is_valid, error_list = active_tab.validate()
        if not is_valid:
            errors_message = "\n- " + "\n- ".join(error_list)
            messagebox.showwarning(
                "Validation Error",
                f"Cannot launch command due to missing parameters:\n{errors_message}",
                parent=self.app,
            )
            return

        cmd_list, cmd_string = self.app.construct_active_command()
        if not cmd_list:
            return

        # Record in history table
        self.current_history_entry_id = self.app.log_console.add_command_entry(
            command_string=cmd_string,
            workdir_path=self.app.current_workdir,
            initial_status="Running",
        )

        # Print header banner in Runlog
        self.app.log_console.append_stream(
            f"\n\x1b[38;2;233;30;140m======================================================================\x1b[0;0m\n"
            f"\x1b[38;5;141m[NFACT GUI] Executing: {cmd_string}\x1b[0;0m\n"
            f"\x1b[38;5;141m[NFACT GUI] Working Dir: {self.app.current_workdir}\x1b[0;0m\n"
            f"\x1b[38;2;233;30;140m======================================================================\x1b[0;0m\n\n"
        )

        # Select Live Runlog tab
        self.app.log_console.notebook.select(0)

        # Update button state & status bar
        self.app.command_bar.set_running_state(True)
        first_token = cmd_list[0]
        self.process_start_time = datetime.now()

        def on_line(output_line: str) -> None:
            self.output_queue.put(("LINE", output_line))

        def on_complete(exit_code: int, duration_sec: float) -> None:
            self.output_queue.put(("DONE", exit_code, duration_sec))

        success = self.app.runner.start_process(
            command_list=cmd_list,
            working_directory=self.app.current_workdir,
            on_line_callback=on_line,
            on_complete_callback=on_complete,
        )

        if success and self.app.runner.process:
            pid = self.app.runner.process.pid
            self.app.status_bar.set_running(first_token, pid=pid)
            self.app.after(50, self.poll_runner_queue)
        else:
            self.app.command_bar.set_running_state(False)
            self.app.status_bar.set_idle("Failed to start")

    def poll_runner_queue(self) -> None:
        """Poll background output queue for stdout lines and completion signals.

        Parameters
        ------------
        None

        Returns
        --------
            None: None object
                Processes lines and reschedules poll if running.
        """
        lines_processed = 0
        while not self.output_queue.empty() and lines_processed < 100:
            item_data = self.output_queue.get_nowait()
            msg_type = item_data[0]

            if msg_type == "LINE":
                self.app.log_console.append_stream(item_data[1])
                lines_processed += 1
            elif msg_type == "DONE":
                self.handle_process_completion(item_data[1], item_data[2])
                return

        if self.app.runner.is_running and self.process_start_time is not None:
            elapsed_delta = datetime.now() - self.process_start_time
            seconds_int = int(elapsed_delta.total_seconds())
            hours_val = seconds_int // 3600
            minutes_val = (seconds_int % 3600) // 60
            secs_val = seconds_int % 60
            self.app.status_bar.update_elapsed(
                f"{hours_val:02d}:{minutes_val:02d}:{secs_val:02d}"
            )
            self.app.after(50, self.poll_runner_queue)
        elif not self.app.runner.is_running and not self.output_queue.empty():
            self.app.after(50, self.poll_runner_queue)

    def handle_process_completion(
        self, exit_code: int, elapsed_duration: float
    ) -> None:
        """Update UI and status bar when the background process finishes.

        Parameters
        ------------
        exit_code: int
            Process return exit code (0 = success).
        elapsed_duration: float
            Elapsed duration in seconds.

        Returns
        --------
            None: None object
                Notifies UI of completion.
        """
        duration_str = f"{elapsed_duration:.1f}s"
        status_text = "Completed (0)" if exit_code == 0 else f"Failed ({exit_code})"

        if self.current_history_entry_id:
            self.app.log_console.update_command_entry(
                self.current_history_entry_id, status_text, duration_str
            )

        self.app.log_console.append_stream(
            f"\n\x1b[38;2;233;30;140m[NFACT GUI] Process finished with exit code {exit_code} (Duration: {duration_str})\x1b[0;0m\n"
        )

        self.app.command_bar.set_running_state(False)
        self.app.status_bar.set_completed(exit_code, duration_str)

        # Refresh log inspector if outdir directory exists
        active_state = self.app.get_active_tab_instance().get_state()
        outdir_val = str(active_state.get("outdir", "")).strip()
        if outdir_val:
            candidate_logs = os.path.join(outdir_val, "nfact", "logs")
            if os.path.isdir(candidate_logs):
                self.app.log_console.set_logs_directory(candidate_logs)
            elif os.path.isdir(os.path.join(outdir_val, "logs")):
                self.app.log_console.set_logs_directory(
                    os.path.join(outdir_val, "logs")
                )

    def stop_process(self) -> None:
        """Send termination signal (SIGINT) to the currently running process.

        Parameters
        ------------
        None

        Returns
        --------
            None: None object
                Terminates process.
        """
        if self.app.runner.is_running:
            self.app.log_console.append_stream(
                "\n\x1b[1;31m[NFACT GUI] Sending SIGINT termination signal...\x1b[0;0m\n"
            )
            self.app.runner.terminate_process()
